test('a model call that throws halts the game with a retry instead of wedging it', async ($, on) => {
  let calls = 0
  const clock = engine(on, () => {
    calls++
    if (calls === 1) throw new Error('boom')
    return 'e5'
  })
  await $.session.start(START)
  const ui = await $.ui.mount({ plugin: 'chessus', surface: 'terminal', ...PANE })
  await ui.press({ key: 'start' })
  for (const key of ['return', 'up', 'up', 'return']) await ui.key({ key, in: 'board' })
  for (let i = 0; i < 6; i++) await clock.advance(500)
  expect(await ui.find({ type: 'Text', text: /Press retry/ })).toBeDefined()
  expect(calls).toBe(1)
  await ui.press({ key: 'retry' })
  await clock.advance(500)
  expect(await ui.find({ type: 'Text', text: /^Your move \((White|Black)\)$/ })).toBeDefined()
})

test('a casual game cannot replace a running tournament game, and pausing freezes the clocks', async ($, on) => {
  const g = gate()
  const clock = engine(on, g.wait)
  await $.session.start(START)
  const ui = await $.ui.mount({ plugin: 'chessus', surface: 'terminal', ...PANE })
  await ui.press({ key: 'nav-settings' })
  await choose(ui, 'tc', 'Blitz 3+2')
  await tournamentSetup(ui)
  await choose(ui, 'pick-model', 'Haiku 4.5')
  await ui.press({ key: 'add' })
  await ui.press({ key: 'add' })
  await ui.press({ key: 'start-tournament' })
  await clock.advance(100)
  await ui.press({ key: 'nav-setup' })
  await choose(ui, 'new-mode', 'Casual game')
  expect(await ui.find({ type: 'Text', text: /A tournament is running\. End it/ })).toBeDefined()
  await ui.press({ key: 'nav-tournament' })
  expect(await ui.find({ type: 'Text', text: /Now playing: round 1/ })).toBeDefined()

  await ui.press({ key: 'pause' })
  g.release('banana')
  await clock.advance(10 * 60_000)
  await ui.press({ key: 'nav-game' })
  expect(await ui.find({ type: 'Text', text: /Paused/ })).toBeDefined()
  expect(await ui.find({ type: 'Text', text: /time forfeit/ })).toBeUndefined()
})


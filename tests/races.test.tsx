import { expect, test } from 'claude-code/testing'

import { HAIKU, PANE, choose, engine, gate, scripted, tournamentSetup } from './kit'

const START = { cwd: '.', surface: 'terminal', isInteractive: true } as const

test('Claude vs Claude waits the spectate delay between moves', async ($, on) => {
  const clock = engine(on, scripted(['e4', 'e5', 'Nf3']))
  await $.session.start(START)
  const ui = await $.ui.mount({ plugin: 'chessus', surface: 'terminal', ...PANE })
  await ui.press({ key: 'nav-settings' })
  await choose(ui, 'spectate', '2s between moves')
  await ui.press({ key: 'nav-setup' })
  await choose(ui, 'white-player', 'Haiku 4.5')
  await ui.press({ key: 'start' })
  await clock.advance(100)
  expect(await ui.find({ type: 'Text', text: /e4/ })).toBeDefined()
  await clock.advance(1500)
  expect(await ui.find({ type: 'Text', text: /e5/ })).toBeUndefined()
  await clock.advance(1000)
  expect(await ui.find({ type: 'Text', text: /e5/ })).toBeDefined()
})

test('a reply that lands after a resign is dropped, and the game is saved once', async ($, on) => {
  const g = gate()
  const clock = engine(on, g.wait)
  await $.session.start(START)
  const ui = await $.ui.mount({ plugin: 'chessus', surface: 'terminal', ...PANE })
  await ui.press({ key: 'nav-setup' })
  await ui.press({ key: 'swap' })
  await ui.press({ key: 'start' })
  await clock.advance(100)
  expect(await ui.find({ type: 'Text', text: /thinking/ })).toBeDefined()
  await ui.press({ key: 'resign' })
  await ui.press({ key: 'resign-yes' })
  g.release('e4')
  await clock.advance(1000)
  expect(await ui.find({ type: 'Text', text: /White \(.+\) wins · Black resigned/ })).toBeDefined()
  expect(await ui.find({ type: 'Text', text: /no moves yet/ })).toBeDefined()
  await ui.press({ key: 'nav-library' })
  expect(await ui.findAll({ type: 'Button', text: /resigned/ })).toHaveLength(1)
})

